"""Export a report as a standalone LaTeX source.

The PDF this plugin ships is produced by ReportLab, because a TeX installation is
not a reasonable dependency for a notebook. That leaves a gap for anyone who does
have TeX: they want the same content as `.tex`. This module closes that gap by
translating the *generated Markdown* — never hand-written Markdown from outside —
into a self-contained `article` document that xelatex/lualatex can typeset with
CJK and Times/serif fonts.

Rules kept deliberately simple so the output stays predictable:
- Only the constructs the notebook itself emits are translated (headings, tables,
  fenced code, quotes, rules, page breaks, bullets, numbered bibliography lines).
- Text is escaped; anything unrecognised passes through as literal text rather
  than being guessed at.
- Inline math written as `$…$` is left as math, because LaTeX is where it belongs.
- Nothing is fetched, executed, or compiled here.
"""
from __future__ import annotations

import re

PREAMBLE = r"""\documentclass[11pt,a4paper]{article}
% Generated by levin-research-notebook. Edit the Markdown source, then regenerate.
\usepackage[margin=22mm]{geometry}
\usepackage{fontspec}
\usepackage{xeCJK}
\usepackage{longtable,booktabs,array}
\usepackage{fancyvrb}
\usepackage{fvextra}
\usepackage{graphicx}
\usepackage{enumitem}
\usepackage[hidelinks]{hyperref}
\usepackage{xcolor}
\usepackage{amsmath}

% Body: Songti (CJK) + Times (Latin); headings: Heiti + Times. Fallbacks keep the
% document compilable on a machine that lacks the exact macOS faces.
% Font resolution is empirical, not aspirational. Measured on macOS 15 with
% tectonic/xetex: the Heiti faces (STHeiti Light.ttc / STHeiti Medium.ttc) are NOT
% reachable by family name, and addressing them by path+FontIndex still produced
% corrupt glyphs in the PDF. Songti.ttc works by path, and its second face is a
% real bold, so headings keep the Heiti *role* (heavier, sans-feel) without
% depending on a face that cannot be loaded. Every fallback below is a chain that
% was actually compiled, not a guess.
\IfFontExistsTF{Songti SC}{%
  \setCJKmainfont[Path=/System/Library/Fonts/Supplemental/,
    BoldFont={Songti.ttc},BoldFeatures={FontIndex=1}]{Songti.ttc}%
}{%
  \setCJKmainfont{Noto Serif CJK SC}%
}
\IfFontExistsTF{Times New Roman}{\setmainfont{Times New Roman}}{\setmainfont{TeX Gyre Termes}}
\IfFontExistsTF{Menlo}{\setmonofont{Menlo}}{\setmonofont{DejaVu Sans Mono}}

\setlength{\parindent}{0pt}
\setlength{\parskip}{5pt}
\renewcommand{\arraystretch}{1.15}
\providecommand{\heiti}{\bfseries}
% `breaklines` is an fvextra (not fancyvrb) option: long command lines must wrap
% instead of running off the page, and a code block must never abort the build.
\DefineVerbatimEnvironment{codeblock}{Verbatim}{fontsize=\small,frame=single,
  framesep=4pt,rulecolor=\color{gray!40},breaklines=true,breakanywhere=true}

\begin{document}
"""

POSTAMBLE = "\n\\end{document}\n"

_ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}

# Inline constructs the notebook emits; order matters (longest marker first).
_INLINE_RULES = (
    (re.compile(r"`([^`]+)`"), lambda m: r"\texttt{" + _escape_plain(m.group(1)) + "}"),
    (re.compile(r"\*\*\*([^*]+)\*\*\*"), lambda m: r"\textbf{\textit{" + _escape_plain(m.group(1)) + "}}"),
    (re.compile(r"\*\*([^*]+)\*\*"), lambda m: r"\textbf{" + _escape_plain(m.group(1)) + "}"),
    (re.compile(r"(?<!\*)\*([^*\n]+)\*(?!\*)"), lambda m: r"\textit{" + _escape_plain(m.group(1)) + "}"),
    (re.compile(r"~~([^~]+)~~"), lambda m: r"\sout{" + _escape_plain(m.group(1)) + "}"),
    (re.compile(r"__([^_]+)__"), lambda m: r"\underline{" + _escape_plain(m.group(1)) + "}"),
    (re.compile(r"\[\^([^\]]+)\]"), lambda m: r"\textsuperscript{" + _escape_plain(m.group(1)) + "}"),
)


# Typographic characters are fragile under xeCJK: a literal en dash between a digit
# and a Latin letter was routed to a CJK face that has no glyph for it and printed
# as U+FFFF. TeX's own dash ligatures are unambiguous, so translate them on the way
# out instead of trusting font fallback.
_TYPOGRAPHIC = {
    "\u2013": "--",      # en dash
    "\u2014": "---",     # em dash
    "\u2018": "`", "\u2019": "'",
    "\u201c": "``", "\u201d": "''",
    "\u2026": "\\ldots{}",
    "\u00a0": "~",
    "\u2009": "\\,",
}


def _escape_plain(text: str) -> str:
    return "".join(_ESCAPES.get(character, _TYPOGRAPHIC.get(character, character))
                   for character in text)


def escape(text: str) -> str:
    """Escape prose while preserving inline math and the inline styles we emit."""
    out: list[str] = []
    position = 0
    for match in re.finditer(r"(?<!\$)\$(?!\$)([^$\n]{1,400})\$(?!\$)", text):
        out.append(_escape_with_styles(text[position:match.start()]))
        out.append("$" + match.group(1) + "$")
        position = match.end()
    out.append(_escape_with_styles(text[position:]))
    return "".join(out)


def _escape_with_styles(text: str) -> str:
    """Apply inline styles first, escaping only the prose between them."""
    if not text:
        return ""
    # Split on the earliest style marker, recurse on the remainder.
    earliest = None
    for pattern, _render in _INLINE_RULES:
        match = pattern.search(text)
        if match and (earliest is None or match.start() < earliest[0].start()):
            earliest = (match, pattern)
    if earliest is None:
        return _escape_plain(text)
    match, pattern = earliest
    rule = next(render for candidate, render in _INLINE_RULES if candidate is pattern)
    return (_escape_with_styles(text[:match.start()]) + rule(match)
            + _escape_with_styles(text[match.end():]))


def _table(block: list[str]) -> str:
    """Translate a pipe table; column widths are left to LaTeX's natural sizing."""
    rows = [[cell.strip() for cell in line.strip().strip("|").split("|")] for line in block]
    rows = [row for row in rows if not all(re.fullmatch(r":?-{2,}:?", cell or "") for cell in row)]
    if not rows:
        return ""
    columns = max(len(row) for row in rows)
    rows = [row + [""] * (columns - len(row)) for row in rows]
    header, body = rows[0], rows[1:]
    spec = " ".join([">{\\raggedright\\arraybackslash}p{\\dimexpr(\\linewidth"
                     f"-{2 * columns}\\tabcolsep)/{columns}\\relax}}"] * columns)
    lines = ["", r"\begin{longtable}{" + spec + "}", r"\toprule",
             " & ".join(escape(cell) for cell in header) + r" \\", r"\midrule", r"\endhead"]
    for row in body:
        lines.append(" & ".join(escape(cell) for cell in row) + r" \\")
    lines += [r"\bottomrule", r"\end{longtable}", ""]
    return "\n".join(lines)


def to_latex(markdown_text: str, title: str) -> str:
    """Return a complete `.tex` document for a generated report."""
    lines = markdown_text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    body: list[str] = [
        r"\begin{center}",
        r"{\bfseries\LARGE " + escape(" ".join(title.splitlines())) + "}",
        r"\end{center}",
        r"\vspace{2pt}",
    ]
    index = 0
    skip_first_heading = True
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        fence = re.match(r"^\s*(`{3,}|~{3,})\s*(\S*)$", line)
        if fence:
            marker = fence.group(1)
            index += 1
            block = []
            while index < len(lines) and not re.match(r"^" + re.escape(marker[0])
                                                      + "{" + str(len(marker)) + r",}\s*$", lines[index]):
                block.append(lines[index])
                index += 1
            index += 1
            body += [r"\begin{codeblock}"] + [ln.replace("\\end{codeblock}", r"\end{codeblock} ") for ln in block] + [r"\end{codeblock}"]
            continue

        if not stripped:
            index += 1
            continue

        heading = re.match(r"^(#{1,6})\s+(.+)$", line)
        if heading:
            level, text = len(heading.group(1)), heading.group(2)
            if level == 1 and skip_first_heading:
                skip_first_heading = False        # the title is already set above
                index += 1
                continue
            skip_first_heading = False
            command = {2: "section", 3: "subsection", 4: "subsubsection"}.get(level, "paragraph")
            body.append("\\" + command + "*{" + escape(text) + "}")
            index += 1
            continue
        skip_first_heading = False

        if stripped.startswith("|") and stripped.endswith("|"):
            block = []
            while index < len(lines) and lines[index].strip().startswith("|"):
                block.append(lines[index])
                index += 1
            body.append(_table(block))
            continue

        if stripped in (r"\pagebreak", r"\newpage"):
            body.append(r"\clearpage")
            index += 1
            continue

        if re.fullmatch(r"(-{3,}|\*{3,}|_{3,})", stripped):
            body += [r"\vspace{4pt}", r"\noindent\rule{\linewidth}{0.6pt}", r"\vspace{4pt}"]
            index += 1
            continue

        display = re.fullmatch(r"\$\$(.+?)\$\$", stripped)
        if display:
            body.append(r"\[" + " ".join(display.group(1).split()) + r"\]")
            index += 1
            continue

        if stripped.startswith(">"):
            quoted = []
            while index < len(lines) and lines[index].strip().startswith(">"):
                quoted.append(lines[index].strip().lstrip(">").strip())
                index += 1
            body.append(r"\begin{quote}" + escape(" ".join(quoted)) + r"\end{quote}")
            continue

        bullet = re.match(r"^(\s*)([-*+]|\d+[.)])\s+(.+)$", line)
        if bullet:
            depth = len(bullet.group(1)) // 2
            ordered = bullet.group(2)[0].isdigit()
            items = []
            while index < len(lines):
                current = re.match(r"^(\s*)([-*+]|\d+[.)])\s+(.+)$", lines[index])
                if not current or len(current.group(1)) // 2 != depth:
                    break
                items.append(current.group(3))
                index += 1
            environment = "enumerate" if ordered else "itemize"
            body += [r"\begin{" + environment + "}[leftmargin=*]"]
            body += [r"\item " + escape(item) for item in items]
            body.append(r"\end{" + environment + "}")
            continue

        paragraph = [stripped]
        index += 1
        while index < len(lines):
            nxt = lines[index]
            if (not nxt.strip() or nxt.strip() in (r"\pagebreak", r"\newpage")
                    or nxt.lstrip().startswith(("#", "|", ">", "```", "~~~"))
                    or re.match(r"^(\s*)([-*+]|\d+[.)])\s+", nxt)):
                break
            paragraph.append(nxt.strip())
            index += 1
        body.append(escape(" ".join(paragraph)))
        body.append("")

    body += [r"\end{document}", ""]
    document = "\n".join(body)
    document = document.replace(r"\end{document}" + "\n\n" + r"\end{document}", r"\end{document}")
    text = PREAMBLE + document
    # \sout needs the ulem package but only when a strike is actually present.
    if r"\sout{" in text:
        text = text.replace(r"\usepackage{xcolor}", "\\usepackage{xcolor}\n\\usepackage[normalem]{ulem}")
    return text
